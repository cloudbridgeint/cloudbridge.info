out.push('-- Repeatable page rows (About + Scholarship)');
for (const it of items) {
  out.push(
    `INSERT INTO page_items (group_key, title, subtitle, body, icon, link_url, link_label, accent, sort_order, active)
SELECT ${q(it.group)}, ${q(it.title ?? '')}, ${q(it.subtitle ?? '')}, ${q(it.body ?? '')}, ${q(it.icon ?? '')}, ${q(it.link_url ?? '')}, ${q(it.link_label ?? '')}, ${q(it.accent ?? '')}, ${it.sort_order}, 1
WHERE NOT EXISTS (SELECT 1 FROM page_items WHERE group_key = ${q(it.group)} AND title = ${q(it.title ?? '')});`
  );
}
out.push('');

writeFileSync(new URL('../migrations/0003_seed_content.sql', import.meta.url), out.join('\n'));
console.log(`Wrote migrations/0003_seed_content.sql — ${DESTINATIONS.length} destinations, ${items.length} page items`);
